const ROWS = {};
for (const [ch, rows] of Object.entries(G)) ROWS[ch] = rows.split('|');

export function textWidth(s, size = 1) { return s.length ? s.length * 6 * size - size : 0; }

export function drawText(ctx, s, x, y, size = 1) {
  for (const ch of s) {
    const rows = ROWS[ch] || ROWS[ch.toUpperCase()];
    if (rows) {
      for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) {
        if (rows[r][c] === '#') ctx.fillRect(x + c * size, y + r * size, size, size);
      }
    }
    x += 6 * size;
  }
}
